-- 4. KUPON DISKON -----------------------------------------------------
create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  kode text not null unique check (kode = upper(kode) and length(kode) between 3 and 30),
  tipe text not null check (tipe in ('persen', 'nominal')),
  nilai integer not null check (nilai > 0),
  maks_diskon integer check (maks_diskon > 0),      -- batas potongan untuk kupon persen (opsional)
  min_belanja integer not null default 0,
  kuota integer check (kuota > 0),                  -- kosong = tanpa batas
  terpakai integer not null default 0,
  berlaku_sampai timestamptz,                       -- kosong = tanpa batas waktu
  aktif boolean not null default true,
  created_at timestamptz not null default now(),
  constraint persen_maks_100 check (tipe <> 'persen' or nilai <= 100)
);
alter table public.coupons enable row level security;
drop policy if exists "Admin kelola kupon" on public.coupons;
create policy "Admin kelola kupon" on public.coupons for all using (public.is_admin()) with check (public.is_admin());
-- Pembeli tidak bisa melihat daftar kupon; pengecekan kode lewat fungsi check_coupon().

insert into public.coupons (kode, tipe, nilai, maks_diskon) values ('TASURA10', 'persen', 10, 500000)
on conflict (kode) do nothing;

create or replace function public.hitung_diskon(c public.coupons, p_subtotal integer)
returns integer language sql immutable as $$
  select least(p_subtotal,
    case when c.tipe = 'persen'
      then least(floor(p_subtotal * c.nilai / 100.0)::integer, coalesce(c.maks_diskon, 2147483647))
      else c.nilai end);
$$;

-- Cek kupon dari halaman checkout: mengembalikan besar diskon atau pesan kesalahan.
create or replace function public.check_coupon(p_kode text, p_subtotal integer)
returns json language plpgsql stable security definer set search_path = public as $$
declare c public.coupons;
begin
  select * into c from public.coupons where kode = upper(trim(p_kode));
  if not found or not c.aktif then
    return json_build_object('valid', false, 'pesan', 'Kode promo tidak ditemukan');
  elsif c.berlaku_sampai is not null and c.berlaku_sampai < now() then
    return json_build_object('valid', false, 'pesan', 'Kode promo sudah kedaluwarsa');
  elsif c.kuota is not null and c.terpakai >= c.kuota then
    return json_build_object('valid', false, 'pesan', 'Kuota kode promo sudah habis');
  elsif p_subtotal < c.min_belanja then
    return json_build_object('valid', false, 'pesan', 'Minimal belanja Rp' || replace(to_char(c.min_belanja, 'FM999,999,999,999'), ',', '.'));
  end if;
  return json_build_object('valid', true, 'kode', c.kode, 'diskon', public.hitung_diskon(c, p_subtotal));
end;
$$;
grant execute on function public.check_coupon(text, integer) to anon, authenticated;

